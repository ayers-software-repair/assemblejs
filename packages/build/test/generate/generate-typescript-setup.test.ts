import { describe, expect, it } from "vitest";
import { generateTypescriptSetup } from "@assemblejs/build";
import type { DiscoveredAssembly } from "@assemblejs/build";

const from = "/p/.assemblejs";
const found = (name: string, view: string, renderer: string): DiscoveredAssembly => ({
  name,
  directory: `/p/src/assemblies/${name}`,
  view: `/p/src/assemblies/${name}/${view}`,
  renderer,
  client: undefined,
  service: undefined,
  styles: [],
});
interface Config {
  readonly compilerOptions?: Record<string, unknown>;
  readonly include?: string[];
  readonly exclude?: string[];
  readonly files?: string[];
  readonly references?: { path: string }[];
}
const setup = (
  assemblies: readonly DiscoveredAssembly[],
  over: Partial<Parameters<typeof generateTypescriptSetup>[0]> = {},
): Record<string, Config> =>
  Object.fromEntries(
    Object.entries(
      generateTypescriptSetup({
        assemblies,
        from,
        browser: [],
        shared: false,
        config: false,
        ...over,
      }),
    ).map(([file, contents]) => {
      // The header is a comment, which a tsconfig may carry; the rest is JSON.
      const [header, ...rest] = contents.split("\n");
      expect(header).toBe("// GENERATED by assemblejs build. Do not edit, and do not commit.");
      return [file, JSON.parse(rest.join("\n")) as Config];
    }),
  );

describe("the TypeScript setup the build writes", () => {
  it("is a solution of the application's project alone, for a project with no JSX and no shared sources", () => {
    const files = setup([found("hello", "hello.html", "html")]);
    expect(Object.keys(files).sort()).toEqual(["tsconfig.app.json", "tsconfig.json"]);
    expect(files["tsconfig.json"]).toEqual({
      files: [],
      references: [{ path: "./tsconfig.app.json" }],
    });
    expect(files["tsconfig.app.json"]?.references).toEqual([]);
  });

  it("gives each owner of JSX a project of its own, named by its documentation, and the application's reads every one", () => {
    const files = setup([
      found("shop", "shop.react.tsx", "react"),
      found("cart", "cart.preact.tsx", "preact"),
      found("search", "search.solid.tsx", "solid"),
      found("meter", "meter.lit.ts", "lit"),
    ]);
    expect(Object.keys(files).sort()).toEqual([
      "tsconfig.app.json",
      "tsconfig.json",
      "tsconfig.preact.json",
      "tsconfig.react.json",
      "tsconfig.solid.json",
    ]);
    expect(files["tsconfig.react.json"]?.compilerOptions).toMatchObject({ jsx: "react-jsx" });
    expect(files["tsconfig.react.json"]?.compilerOptions).not.toHaveProperty("jsxImportSource");
    expect(files["tsconfig.preact.json"]?.compilerOptions).toMatchObject({
      jsx: "react-jsx",
      jsxImportSource: "preact",
    });
    expect(files["tsconfig.solid.json"]?.compilerOptions).toMatchObject({
      jsx: "preserve",
      jsxImportSource: "solid-js",
    });
    expect(files["tsconfig.app.json"]?.references).toEqual([
      { path: "./tsconfig.preact.json" },
      { path: "./tsconfig.react.json" },
      { path: "./tsconfig.solid.json" },
    ]);
    expect(files["tsconfig.json"]?.references?.at(-1)).toEqual({ path: "./tsconfig.app.json" });
  });

  it("puts an assembly's directory, its registry module and its browser module in its owner's project, by the build's own definition of whose a file is", () => {
    const files = setup(
      [
        found("shop", "shop.react.tsx", "react"),
        found("cart", "cart.preact.tsx", "preact"),
        found("meter", "meter.lit.ts", "lit"),
        found("hello", "hello.html", "html"),
      ],
      { browser: ["shop", "cart", "meter"] },
    );
    expect(files["tsconfig.react.json"]?.include).toEqual([
      "../src/assemblies/shop/**/*",
      "../src/**/*.react.tsx",
      "./assemblies.react.ts",
      "./client/shop.ts",
    ]);
    // A file that names another owner, wherever it stands, is that owner's and not this one's.
    expect(files["tsconfig.react.json"]?.exclude).toEqual(["../src/**/*.preact.tsx"]);
    expect(files["tsconfig.preact.json"]?.exclude).toEqual(["../src/**/*.react.tsx"]);
    // The application's project holds the server, the generated modules, and every assembly
    // with no JSX of its own, with its browser module.
    expect(files["tsconfig.app.json"]?.include).toEqual([
      "../src/server.ts",
      "./assemblies.ts",
      "./pages.ts",
      "./apis.ts",
      "./project.ts",
      "./client.ts",
      "./client/meter.ts",
      "../src/assemblies/meter/**/*",
      "../src/assemblies/hello/**/*",
    ]);
    expect(files["tsconfig.app.json"]?.exclude).toEqual([
      "../src/**/*.preact.tsx",
      "../src/**/*.react.tsx",
    ]);
  });

  it("writes the shared project only when there is something in it, and every other project reads it", () => {
    const assemblies = [found("shop", "shop.react.tsx", "react")];
    expect(setup(assemblies)).not.toHaveProperty("tsconfig.shared.json");
    const files = setup(assemblies, { shared: true, config: true });
    expect(files["tsconfig.shared.json"]).toEqual({
      compilerOptions: expect.objectContaining({ jsx: "react-jsx", composite: true }) as unknown,
      include: ["../src/**/*"],
      exclude: ["../src/assemblies", "../src/server.ts", "../src/**/*.react.tsx"],
    });
    expect(files["tsconfig.react.json"]?.references).toEqual([{ path: "./tsconfig.shared.json" }]);
    expect(files["tsconfig.app.json"]?.references).toEqual([
      { path: "./tsconfig.shared.json" },
      { path: "./tsconfig.react.json" },
    ]);
    expect(files["tsconfig.app.json"]?.include).toContain("../assemblejs.config.ts");
    expect(files["tsconfig.json"]?.references).toHaveLength(3);
  });

  it("checks as the bundler compiles, and emits only declarations, each project into its own directory", () => {
    const files = setup([found("shop", "shop.react.tsx", "react")], { shared: true });
    for (const name of ["shared", "react", "app"]) {
      expect(files[`tsconfig.${name}.json`]?.compilerOptions, name).toMatchObject({
        target: "ES2022",
        module: "ESNext",
        moduleResolution: "bundler",
        strict: true,
        isolatedModules: true,
        skipLibCheck: true,
        composite: true,
        emitDeclarationOnly: true,
        rootDir: "..",
        outDir: `./types/${name}`,
        tsBuildInfoFile: `./types/${name}.tsbuildinfo`,
      });
    }
  });
});
