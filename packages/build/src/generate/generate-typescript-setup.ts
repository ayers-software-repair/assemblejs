import { relative, resolve } from "node:path";
import type { DiscoveredAssembly } from "../discovery/discovered-assembly.js";
import { jsxOwner } from "../discovery/jsx-owner.js";

// The line that heads each written configuration. A tsconfig is read as JSON with comments.
const HEADER = "// GENERATED by assemblejs build. Do not edit, and do not commit.";

// How each owner's JSX is checked, by its own documentation: Preact and Solid name the module
// their JSX comes from; Solid's is left as written, for its own compiler; React's is the default.
const JSX: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  react: { jsx: "react-jsx" },
  preact: { jsx: "react-jsx", jsxImportSource: "preact" },
  solid: { jsx: "preserve", jsxImportSource: "solid-js" },
};

/**
 * The compiler options every project shares. The target and the resolution are the bundler's,
 * so what the compiler accepts is what the build compiles; each file is checked on its own, as
 * the bundler compiles it; a project emits declarations only, into the generated directory,
 * which is what lets the projects reference each other and an editor find which one a file is
 * in; and the libraries of other packages are not checked, as they are not this project's to fix.
 */
const compilerOptions = (
  name: string,
  owner: string | undefined,
): Readonly<Record<string, unknown>> => ({
  target: "ES2022",
  module: "ESNext",
  moduleResolution: "bundler",
  lib: ["ES2022", "DOM", "DOM.Iterable"],
  ...(owner === undefined ? JSX["react"] : JSX[owner]),
  strict: true,
  isolatedModules: true,
  skipLibCheck: true,
  composite: true,
  emitDeclarationOnly: true,
  rootDir: "..",
  outDir: `./types/${name}`,
  tsBuildInfoFile: `./types/${name}.tsbuildinfo`,
});

const written = (config: unknown): string => `${HEADER}\n${JSON.stringify(config, null, 2)}\n`;

/**
 * The TypeScript setup of a project, as the files the build writes into the generated
 * directory: a solution, and one project for each owner of JSX the assemblies have, so no file
 * of a user's needs a line saying whose JSX it is. The build's own definition of whose a file
 * is decides which project holds it: an assembly's directory is its renderer's, and a `.tsx`
 * outside every assembly that names a framework is that framework's. The sources outside the
 * assemblies are a project every other reads, written only when there are any; the server
 * file, the generated modules and the config are the application's project, which reads every
 * other. Each owner's registry module and browser modules are in the owner's project, so the
 * render and hydrate calls written for a view are checked against the view's own framework.
 * The user's root `tsconfig.json` names the solution and nothing else.
 */
export function generateTypescriptSetup(options: {
  readonly assemblies: readonly DiscoveredAssembly[];
  /** The generated directory the setup is written to. */
  readonly from: string;
  /** The names of the assemblies with a browser module, `client/<name>.ts`. */
  readonly browser: readonly string[];
  /** Whether the project has sources outside its assemblies and its server file. */
  readonly shared: boolean;
  /** Whether the project has an assemblejs.config.ts. */
  readonly config: boolean;
}): Readonly<Record<string, string>> {
  const { assemblies, from, browser, shared, config } = options;
  const owners = [
    ...new Set(assemblies.flatMap((assembly) => jsxOwner(assembly.renderer) ?? [])),
  ].sort();
  const named = (owner: string): string => `../src/**/*.${owner}.tsx`;
  const others = (owner: string | undefined): string[] =>
    owners.filter((one) => one !== owner).map(named);
  const directory = (assembly: DiscoveredAssembly): string =>
    `${relative(from, resolve(assembly.directory)).split("\\").join("/")}/**/*`;
  const client = (assembly: DiscoveredAssembly): string[] =>
    browser.includes(assembly.name) ? [`./client/${assembly.name}.ts`] : [];
  const files: Record<string, string> = {};
  const references: { readonly path: string }[] = [];

  if (shared) {
    files["tsconfig.shared.json"] = written({
      compilerOptions: compilerOptions("shared", undefined),
      include: ["../src/**/*"],
      exclude: ["../src/assemblies", "../src/server.ts", ...others(undefined)],
    });
    references.push({ path: "./tsconfig.shared.json" });
  }
  const sharedOnly = [...references];
  for (const owner of owners) {
    const own = assemblies.filter((assembly) => jsxOwner(assembly.renderer) === owner);
    files[`tsconfig.${owner}.json`] = written({
      compilerOptions: compilerOptions(owner, owner),
      include: [
        ...own.map(directory),
        named(owner),
        `./assemblies.${owner}.ts`,
        ...own.flatMap(client),
      ],
      exclude: others(owner),
      references: sharedOnly,
    });
    references.push({ path: `./tsconfig.${owner}.json` });
  }
  const unowned = assemblies.filter((assembly) => jsxOwner(assembly.renderer) === undefined);
  files["tsconfig.app.json"] = written({
    compilerOptions: compilerOptions("app", undefined),
    include: [
      "../src/server.ts",
      "./assemblies.ts",
      "./pages.ts",
      "./apis.ts",
      "./project.ts",
      ...(browser.length === 0 ? [] : ["./client.ts"]),
      ...unowned.flatMap(client),
      ...unowned.map(directory),
      ...(config ? ["../assemblejs.config.ts"] : []),
    ],
    exclude: others(undefined),
    references,
  });
  files["tsconfig.json"] = written({
    files: [],
    references: [...references, { path: "./tsconfig.app.json" }],
  });
  return files;
}
