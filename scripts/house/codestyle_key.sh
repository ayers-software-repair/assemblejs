# The one reader for a repo's committed .codestyle, sourced by every gate so the parsing lives once
# rather than copied into each script. key=value lines, not sourced as shell.
#
# Fail-closed: an absent file or a missing key returns non-zero, never a default, so a repo cannot
# silently gate itself under the wrong policy. The KEY must always be present. The VALUE may be empty
# ONLY when the caller passes a non-empty second argument - a key whose empty value is a deliberate
# choice (gates_since's "no floor", the identity keys' "no ban"/"no exclusion"). A key whose empty
# value would be meaningless (length_ceiling, open_source) is read with no second argument, and an
# empty value there fails closed.
#
# This file only defines a function; it is sourced, so it carries no `set` line of its own - that
# would leak into whatever sources it.

codestyle_key() {
  local key="$1" allow_empty="${2:-}" root cfg val
  root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
  cfg="$root/.codestyle"
  [ -f "$cfg" ] || { echo "no .codestyle at $root - cannot read key '${key}' (fail-closed)" >&2; return 1; }
  if ! grep -Eq "^${key}=" "$cfg"; then echo ".codestyle has no ${key} key (fail-closed)" >&2; return 1; fi
  val=$(grep -E "^${key}=" "$cfg" | head -n1 | cut -d= -f2-)
  [ -n "$val" ] || [ -n "$allow_empty" ] || { echo ".codestyle has an empty '${key}' (fail-closed)" >&2; return 1; }
  printf '%s' "$val"
}

# The opt-in reader for a gate that must stay silent until a repo turns it on. This is the ONE
# deliberate exception to the fail-closed law above: an absent file, an absent key, an empty value
# and any value other than the string "true" all mean OFF (return 1), never an error. The reason is
# adoption - the opt-in gates ship in the kit before any repo has keyed them, and a fail-closed read
# would red every consumer the moment it took the tag carrying the gate. Only a key present and
# exactly "true" turns the gate on (return 0). Do not "correct" this to fail closed.
codestyle_opt_in() {
  local key="$1" val
  val=$(codestyle_key "$key" allow-empty 2>/dev/null) || return 1
  [ "$val" = "true" ]
}

# A path the content gates never judge, regardless of config: a vendored tree or a generated file.
# Mirrors check-length's unconditional exemptions (vendor/, node_modules/, first-lines
# <auto-generated), plus thirdparty/, so a consumer's opt-in gate does not red on code it did not
# author. Reads the file from disk, which the file-scoped gates already have; length reads git revs
# and so keeps its own copy. Returns 0 when the path is exempt.
codestyle_exempt() {
  local path="$1"
  case "$path" in
    vendor/*|*/vendor/*|node_modules/*|*/node_modules/*|thirdparty/*|*/thirdparty/*) return 0 ;;
  esac
  [ -f "$path" ] || return 1
  # grep's status alone decides: in a pipe under pipefail, head killed after grep -q matched would
  # turn the marker into a miss. An unreadable file gives grep no input and is not exempt.
  grep -qF -- '<auto-generated' < <(head -n 3 -- "$path" 2>/dev/null)
}

# Run directly with --self-test; sourced (the normal path) this block is skipped even when the
# sourcing gate was itself invoked with --self-test, since a sourced file inherits the caller's
# positional parameters - the $0/BASH_SOURCE guard is what tells the two apart.
if [ "${BASH_SOURCE[0]}" = "$0" ] && [ "${1:-}" = "--self-test" ]; then
  set -euo pipefail
  d=$(mktemp -d); trap 'rm -rf "$d"' EXIT
  fail() { echo "codestyle_key self-test FAILED: $*" >&2; exit 1; }
  git -C "$d" init -q; git -C "$d" config user.email t@t.t; git -C "$d" config user.name t
  ( cd "$d" && codestyle_key any 2>/dev/null ) && fail "returned with no .codestyle (should fail closed)"
  printf 'present=value\nempty=\n' > "$d/.codestyle"; git -C "$d" add .codestyle; git -C "$d" commit -qm cfg
  [ "$( cd "$d" && codestyle_key present )" = "value" ] || fail "did not return a present value"
  ( cd "$d" && codestyle_key missing 2>/dev/null ) && fail "returned on a missing key (should fail closed)"
  ( cd "$d" && codestyle_key empty 2>/dev/null ) && fail "returned an empty value with no allow-empty (should fail closed)"
  [ -z "$( cd "$d" && codestyle_key empty allow-empty )" ] || fail "allow-empty did not accept an empty value"

  # codestyle_opt_in: OFF for absent file, absent key, empty value and a non-true value; ON only for
  # exactly "true". Proven against a known-off and a known-on case, so the adoption exception is
  # pinned here rather than implied by each opt-in gate.
  e=$(mktemp -d); trap 'rm -rf "$d" "$e"' EXIT
  git -C "$e" init -q; git -C "$e" config user.email t@t.t; git -C "$e" config user.name t
  ( cd "$e" && codestyle_opt_in one_item ) && fail "opt_in returned on with no .codestyle (should be off)"
  printf 'one_item=false\ncomment_law=true\nempty=\n' > "$e/.codestyle"; git -C "$e" add .codestyle; git -C "$e" commit -qm cfg
  ( cd "$e" && codestyle_opt_in missing ) && fail "opt_in returned on for an absent key"
  ( cd "$e" && codestyle_opt_in one_item ) && fail "opt_in returned on for a false value"
  ( cd "$e" && codestyle_opt_in empty ) && fail "opt_in returned on for an empty value"
  ( cd "$e" && codestyle_opt_in comment_law ) || fail "opt_in returned off for a true value"

  # codestyle_exempt reads a generated marker on line 1 the same when the first lines are longer
  # than a pipe holds, and exempts nothing without the marker.
  printf -v long '%200000s' ''
  { printf '// <auto-generated />\n'; printf '%s\n' "$long" "$long" "$long"; } > "$d/gen.cs"
  { printf '// hand-written\n'; printf '%s\n' "$long" "$long" "$long"; } > "$d/hand.cs"
  codestyle_exempt "$d/gen.cs" || fail "a generated file with long first lines was not exempt"
  codestyle_exempt "$d/hand.cs" && fail "a hand-written file with long first lines was exempt"

  echo "codestyle_key self-test: fails closed on a missing file, missing key and empty value; returns a present value; allow-empty accepts an empty one; opt_in is off unless a key is present and true; the generated marker is read the same behind long lines"
  exit 0
fi
